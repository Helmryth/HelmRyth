// Every package the Electron main process imports must actually be inside the
// packaged app.
//
// electron-builder copies what its `files` list selects and nothing else. The
// main process then resolves its imports at runtime, from inside the asar,
// against whatever was copied. When those two disagree the app does not
// degrade — it dies before a window is ever created:
//
//   A JavaScript error occurred in the main process
//   Error [ERR_MODULE_NOT_FOUND]: Cannot find package 'zod' imported from
//   /tmp/.mount_.../resources/app.asar/electron/managed-composio.mjs
//
// Nothing short of packaging the app and launching it notices, which on this
// repository means a 25-minute Ubuntu CI job — and only that job, because the
// macOS and Windows package builds are not smoke-launched at all. This gate
// asks the same question statically, in milliseconds, on every platform.
//
// The contract it enforces has two halves, because either one alone is enough
// to break a launch:
//   1. the package is in `dependencies`, so a production install has it, and
//   2. some `files` entry positively selects it, so packaging copies it.

import { readFileSync, readdirSync } from "node:fs";
import { builtinModules } from "node:module";
import { extname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { parse } from "yaml";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));

/** Resolution is by package, not by subpath: `zod/v4` and `zod` are both
 * satisfied by shipping `zod`. Scoped names keep two segments. */
export function packageOf(specifier) {
  const parts = specifier.split("/");
  return specifier.startsWith("@") ? parts.slice(0, 2).join("/") : parts[0];
}

/** Node resolves these without anything being copied. `node:`-prefixed and
 * bare spellings are both in use in this tree, and `electron` itself is
 * provided by the runtime rather than by the app bundle. */
export function isProvidedByRuntime(specifier) {
  if (specifier.startsWith("node:")) return true;
  if (specifier === "electron") return true;
  return builtinModules.includes(packageOf(specifier));
}

const IMPORT_PATTERNS = [
  // import x from "p" / export { x } from "p" / import "p"
  /(?:^|[\s;}])(?:import|export)\s+(?:[^"';]*?\sfrom\s+)?["']([^"']+)["']/gm,
  // await import("p")
  /\bimport\s*\(\s*["']([^"']+)["']\s*\)/g,
  // require("p")
  /\brequire\s*\(\s*["']([^"']+)["']\s*\)/g,
];

/** Bare specifiers only — a relative or absolute path is part of the app and
 * is copied by the same `electron/**` pattern that copied its importer. */
export function bareSpecifiers(source) {
  const found = new Set();
  for (const pattern of IMPORT_PATTERNS) {
    for (const match of source.matchAll(pattern)) {
      const specifier = match[1];
      if (specifier.startsWith(".") || specifier.startsWith("/")) continue;
      found.add(specifier);
    }
  }
  return [...found].sort();
}

const PACKAGED_EXTENSIONS = new Set([".mjs", ".cjs", ".js"]);
const TEST_MODULE = /\.(?:test|node-test|spec)\.[cm]?js$/;

/** The modules electron-builder copies under `electron/**`, minus the tests it
 * excludes. `electron/vendor/` is generated by `pnpm build:updater` and is
 * absent from a clean checkout; whatever is present is scanned. */
export function packagedModules(scanRoot = root) {
  const found = [];
  const walk = (directory) => {
    let entries;
    try {
      entries = readdirSync(directory, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) {
        if (entry.name === "node_modules" || entry.name === "resources") continue;
        walk(path);
      } else if (PACKAGED_EXTENSIONS.has(extname(entry.name)) && !TEST_MODULE.test(entry.name)) {
        found.push(path);
      }
    }
  };
  walk(join(scanRoot, "electron"));
  return found;
}

/** Whether an electron-builder `files` entry positively selects a package.
 *
 * Deliberately narrow: it recognises an explicit `node_modules/<pkg>` include
 * and nothing cleverer. Reimplementing electron-builder's full glob and
 * negation semantics here would mean this gate could be wrong in the same
 * direction as the manifest, which is the one failure it must not have. An
 * explicit entry is unambiguous under every one of those semantics. */
export function selectsPackage(patterns, name) {
  return patterns.some((pattern) => {
    if (pattern.startsWith("!")) return false;
    const cleaned = pattern.replace(/^\.\//, "");
    return cleaned === `node_modules/${name}` || cleaned.startsWith(`node_modules/${name}/`);
  });
}

/** Reduce a parsed `files:` list to the globs this gate reasons about.
 *
 * electron-builder accepts either a bare glob or a `{from, to, filter}` object
 * in that list. The object form names a source directory to copy wholesale and
 * never a package glob, so it carries nothing for this check. Both shapes are
 * resolved here, where the YAML is read, and everything downstream works with
 * a list of strings rather than re-asking what it was handed. */
export function includePatterns(files) {
  const patterns = [];
  for (const entry of Array.isArray(files) ? files : []) {
    if (entry === null || entry instanceof Object) continue;
    patterns.push(String(entry));
  }
  return patterns;
}

/** Imports that are reached only when the app is NOT packaged, together with
 * what the packaged path uses instead.
 *
 * An exemption that outlives its import is a lie the next reader inherits, so
 * each entry is checked in both directions: it excuses the import it names,
 * and it becomes a finding of its own if that import is gone. The list cannot
 * quietly accumulate. */
export const DEVELOPMENT_ONLY_IMPORTS = [
  {
    module: "electron/cua.mjs",
    specifier: "@trycua/cua-driver/embedded",
    reason: "reached only under `if (!app.isPackaged)`; the packaged branch imports resourcesPath/cua-sdk/cua-sdk.mjs, staged by extraResources",
  },
  {
    module: "electron/cua.mjs",
    specifier: "@trycua/cua-driver/electron",
    reason: "reached only under `if (!app.isPackaged)`; the packaged branch imports resourcesPath/cua-sdk/cua-sdk.mjs, staged by extraResources",
  },
];

/** Minimal glob to RegExp for the shapes electron-builder's `files` list uses:
 * `**` crosses directory boundaries, `*` does not, everything else is literal.
 * Deliberately small — it exists to check this repository's own patterns, not
 * to reimplement electron-builder. */
export function globToRegExp(pattern) {
  let out = "^";
  let i = 0;
  while (i < pattern.length) {
    if (pattern.startsWith("**/", i)) { out += "(?:.*/)?"; i += 3; continue; }
    if (pattern.startsWith("**", i)) { out += ".*"; i += 2; continue; }
    if (pattern[i] === "*") { out += "[^/]*"; i += 1; continue; }
    out += pattern[i].replace(/[.+?^${}()|[\]\\]/g, "\\$&");
    i += 1;
  }
  return new RegExp(`${out}$`);
}

/** Whether the packaging manifest's `files` list excludes this path. */
export function excludedByManifest(files, name) {
  return includePatterns(files.filter((entry) => entry !== null && !(entry instanceof Object)))
    .filter((entry) => entry.startsWith("!"))
    .some((entry) => globToRegExp(entry.slice(1)).test(name));
}

export function packagedImportFindings({ modules, manifest, dependencies, devDependencies, exemptions = DEVELOPMENT_ONLY_IMPORTS }) {
  const excused = new Set(exemptions.map((entry) => `${entry.module} ${entry.specifier}`));
  const claimed = new Set();
  const patterns = includePatterns(manifest?.files);
  const findings = [];
  for (const { name, source } of modules) {
    for (const specifier of bareSpecifiers(source)) {
      if (isProvidedByRuntime(specifier)) continue;
      const key = `${name} ${specifier}`;
      if (excused.has(key)) {
        claimed.add(key);
        continue;
      }
      const pkg = packageOf(specifier);
      if (!dependencies.includes(pkg)) {
        findings.push({
          name,
          specifier,
          reason: devDependencies.includes(pkg)
            ? `\`${pkg}\` is a devDependency, so a production install does not have it`
            : `\`${pkg}\` is in neither dependencies nor devDependencies`,
        });
        continue;
      }
      if (!selectsPackage(patterns, pkg)) {
        findings.push({
          name,
          specifier,
          reason: `no electron-builder \`files\` entry selects node_modules/${pkg}, so packaging omits it`,
        });
      }
    }
  }
  for (const entry of exemptions) {
    const key = `${entry.module} ${entry.specifier}`;
    if (!claimed.has(key)) {
      findings.push({
        name: "scripts/check-packaged-imports.mjs",
        specifier: entry.specifier,
        reason: `DEVELOPMENT_ONLY_IMPORTS excuses ${entry.module}, which no longer imports it — delete the exemption`,
      });
    }
  }
  return findings;
}

export function scanRepository(scanRoot = root) {
  const manifest = parse(readFileSync(join(scanRoot, "electron-builder.yml"), "utf8"));
  const pkg = JSON.parse(readFileSync(join(scanRoot, "package.json"), "utf8"));
  const modules = packagedModules(scanRoot).map((path) => ({
    name: relative(scanRoot, path).split(sep).join("/"),
    source: readFileSync(path, "utf8"),
  }));
  return {
    scanned: modules.length,
    findings: packagedImportFindings({
      modules,
      manifest,
      dependencies: Object.keys(pkg.dependencies ?? {}),
      devDependencies: Object.keys(pkg.devDependencies ?? {}),
    }),
  };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const { scanned, findings } = scanRepository();
  if (scanned === 0) {
    console.error("Packaged-import check found no modules to scan — that is a broken scan, not a clean one.");
    process.exit(1);
  }
  if (findings.length > 0) {
    console.error(`Packaged main-process imports would not resolve (${findings.length}):`);
    for (const finding of findings) console.error(`- ${finding.name} imports "${finding.specifier}" — ${finding.reason}`);
    console.error("\nThe packaged app fails at launch with ERR_MODULE_NOT_FOUND before any window opens.");
    process.exit(1);
  }
  console.log(`Packaged-import check passed across ${scanned} main-process modules.`);
}
